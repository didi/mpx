const fs = require('fs')
const assert = require('assert')
const path = require('path')
const root = '/private/tmp/mpx-address-dialog-validation'
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const component = 'components/address-dialog8b9859e2/index'
const ali = read(`dist-ali/${component}.axml`)
const wx = read(`dist-wx/${component}.wxml`)
assert(!/\w+@(wx|ali)|wx:/.test(ali), 'ali must contain compiled template')
assert.equal((ali.match(/mpx-scrollbar-hidden/g) || []).length, 1)
assert(ali.includes('<scroll-view scroll-x="{{true}}" class="mpx-scrollbar-hidden'))
assert(/<scroll-view[^>]*class="audit [^"]*"/.test(ali))
assert(/<scroll-view[^>]*class="list [^"]*"/.test(ali))
assert.equal((ali.match(/enableNative="{{isIOS}}"/g) || []).length, 2)
assert(!/always-embed|enhanced|show-scrollbar|adjust-position|keyboardheightchange/.test(ali))
assert(/<view[^>]*disable-scroll="{{true}}"[^>]*class="mask [^"]*"\/><view[^>]*class="dialog /.test(ali))
assert.equal((wx.match(/always-embed="{{true}}"/g) || []).length, 2)
assert(wx.includes('catchtouchmove="stopMove"'))
assert(wx.includes('show-scrollbar="{{false}}" enhanced="{{true}}"'))
assert(!/enableNative|disable-scroll|adjust-position/.test(wx))
assert(read('dist-ali/app.acss').startsWith('@import "./mpx-ali-compat.acss";'))
assert(read('dist-ali/mpx-ali-compat.acss').includes('.mpx-scrollbar-hidden::-webkit-scrollbar'))
assert(!read('dist-ali/mpx-ali-compat.acss').includes('\n::-webkit-scrollbar'))
assert(read(`dist-ali/${component}.acss`).includes('.audit._8b9859e2'))
assert(!fs.existsSync(path.join(root, 'dist-wx/mpx-ali-compat.acss')))
for (const mode of ['wx', 'ali']) {
  const stats = JSON.parse(read(`app-stats-${mode}.json`))
  assert.equal(stats.errors.length, 0)
  assert.equal(stats.warnings.length, 0)
}
const stats = JSON.parse(read('app-stats-ali.json'))
assert(stats.modules.some(m => (m.identifier || '').includes(require('path').resolve(__dirname, '../../../../../node_modules/@mpxjs/api-proxy/src/platform/api/system/index.ali.js'))))
assert(stats.modules.some(m => (m.identifier || '').includes(require('path').resolve(__dirname, '../../../../../node_modules/@mpxjs/core/src/core/proxy.js'))))
console.log('PASS: wx/ali templates, sibling mask/dialog, scoped styles, selective scrollbar class, App style import and local runtime module paths')

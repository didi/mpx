const fs = require('fs')
const path = require('path')
const assert = require('assert')
const root = __dirname
function read(file) { return fs.readFileSync(path.join(root, file), 'utf8') }
function template(mode, ext) {
  const dir = fs.readdirSync(path.join(root, 'dist', mode, 'components')).find(name => name.startsWith('address-dialog'))
  return { content: read(`dist/${mode}/components/${dir}/index.${ext}`), dir }
}
const ali = template('ali', 'axml')
const wx = template('wx', 'wxml')
assert(ali.content.includes('a:if="{{visible}}"'))
assert(!/@ali|@wx|wx:|show-scrollbar|enhanced|adjust-position/.test(ali.content))
assert.equal((ali.content.match(/enableNative="{{isIOS}}"/g) || []).length, 2)
assert(ali.content.includes('type="number"'))
assert.equal((ali.content.match(/mpx-scrollbar-hidden/g) || []).length, 1)
assert(ali.content.includes('scroll-x="{{true}}" class="mpx-scrollbar-hidden'))
assert(/<scroll-view[^>]*class="audit[^>]*>/.test(ali.content))
assert(!ali.content.match(/<scroll-view[^>]*class="audit[^>]*>/)[0].includes('mpx-scrollbar-hidden'))
assert(ali.content.includes('disable-scroll="{{true}}" class="mask'))
assert(/class="mask[^>]*><\/view><view catchTap="stopMove" class="dialog/.test(ali.content))
assert(ali.content.includes('onTap="close"'))
assert(ali.content.includes('catchTouchMove="stopMove"'))
assert(wx.content.includes('catchtouchmove="stopMove" class="root"'))
assert(wx.content.includes('show-scrollbar="{{false}}" enhanced="{{true}}"'))
assert(!/enableNative|disable-scroll|adjust-position|@ali|@wx/.test(wx.content))
assert.equal((wx.content.match(/type="number"/g) || []).length, 1)
assert(read('dist/ali/app.acss').startsWith('@import "./mpx-ali-compat.acss";'))
assert(read('dist/ali/app.acss').includes('.app-probe'))
assert(read('dist/ali/mpx-ali-compat.acss').includes('.mpx-scrollbar-hidden::-webkit-scrollbar'))
assert(!fs.existsSync(path.join(root, 'dist/wx/mpx-ali-compat.acss')))
const aliStyle = read(`dist/ali/components/${ali.dir}/index.acss`)
assert(/\.audit\._/.test(aliStyle))
assert(!aliStyle.includes('webkit-scrollbar'))
;['wx', 'ali'].forEach(mode => {
  const stats = JSON.parse(read(`stats-${mode}.json`))
  assert.equal(stats.errors.length, 0)
  assert.equal(stats.warnings.length, 0)
  assert(stats.modules.some(m => (m.identifier || '').includes('/lib/template-compiler/index.js')))
  assert(stats.modules.some(m => (m.identifier || '').includes('/lib/style-compiler/index.js')))
  const modules = JSON.parse(read(`modules-${mode}.json`))
  assert(modules.some(file => file.includes(require('path').resolve(__dirname, '../../../../../node_modules/@mpxjs/core/src/index.js'))))
  assert(modules.some(file => file.includes(require('path').resolve(__dirname, '../../../../../node_modules/@mpxjs/api-proxy/src/platform/api/system/index') + (mode === 'ali' ? '.ali' : '') + '.js')))
  console.log(`${mode}: templates, component assets, compiler chain, core/api-proxy module paths checked; 0 errors / 0 warnings`)
})

describe('task board through compiled WXML event bindings', () => {
  test('valid, invalid and missing route category; exact initial records and count', () => {
    const page = mount('pages/task-board')
    page.load()
    expect(page.public.category).toBe('全部')
    expect(page.public.visibleTasks.map(task => task.taskKey)).toEqual(['t1', 't2', 't3'])
    expect(page.public.visibleTasks.map(task => task.completed)).toEqual([false, false, true])
    page.load({ category: '工作' })
    expect(page.public.visibleTasks.length).toBe(1)
    page.load({ category: '生活' })
    expect(page.public.visibleTasks.length).toBe(2)
    page.load({ category: '非法值' })
    expect(page.public.category).toBe('全部')
  })

  test('task toggles twice without losing other records', () => {
    const page = mount('pages/task-board')
    const task = page.public.visibleTasks[0]
    fire(page, 'task-card', 'tap', { item: task })
    expect(task.completed).toBe(true)
    fire(page, 'task-card', 'tap', { item: task })
    expect(task.completed).toBe(false)
    expect(page.public.visibleTasks.length).toBe(3)
  })

  test('empty filtered list exposes the actual empty-state condition and text', () => {
    const page = mount('pages/task-board')
    fire(page, 'segmented-control', 'change', {}, { controlKey: 'category', value: '无匹配分类' })
    expect(page.public.visibleTasks).toEqual([])
    expect(evaluate(findNode(page, 'board-empty').attributes['wx:if'], page)).toBe(true)
    expect(page.wxml).toContain('暂无任务')
  })

  test('success refresh restores data, resets rating, and ends feedback', async () => {
    const page = mount('pages/task-board')
    page.load({ category: '生活' })
    fire(page, 'rating-selector', 'change', {}, { ratingKey: 'board', value: 4 })
    fire(page, 'task-card', 'tap', { item: page.public.visibleTasks[0] })
    fire(page, 'scroll-view', 'scrolltolower')
    const request = fire(page, 'scroll-view', 'refresherrefresh')
    expect(page.public.refreshing).toBe(true)
    const before = copy(page.public.visibleTasks)
    fire(page, 'scroll-view', 'scrolltolower')
    expect(copy(page.public.visibleTasks)).toEqual(before)
    await fire(page, 'scroll-view', 'refresherrefresh')
    page.flushTimers()
    await request
    expect(page.public.refreshing).toBe(false)
    expect(page.public.boardRating).toBe(0)
    expect(page.public.category).toBe('生活')
    expect(page.public.visibleTasks.map(task => task.taskKey)).toEqual(['t2', 't3'])
    expect(page.public.visibleTasks.map(task => task.completed)).toEqual([false, true])
    expect(page.public.refreshError).toBe('')
  })

  test('injected asynchronous failure preserves tasks/rating and remains interactive', async () => {
    const page = mount('pages/task-board')
    page.load({ refreshFail: '1' })
    fire(page, 'rating-selector', 'change', {}, { ratingKey: 'board', value: 3 })
    fire(page, 'scroll-view', 'scrolltolower')
    const before = copy(page.public.visibleTasks)
    const request = fire(page, 'scroll-view', 'refresherrefresh')
    expect(page.public.refreshing).toBe(true)
    page.flushTimers()
    await request
    expect(page.public.refreshing).toBe(false)
    expect(page.public.boardRating).toBe(3)
    expect(copy(page.public.visibleTasks)).toEqual(before)
    expect(page.public.refreshError).toContain('刷新失败')
    fire(page, 'task-card', 'tap', { item: page.public.visibleTasks[0] })
    expect(page.public.visibleTasks[0].completed).toBe(!before[0].completed)
    fire(page, 'scroll-view', 'scrolltolower')
    expect(page.public.visibleTasks.length).toBe(before.length + 2)
    page.load({ refreshFail: '0' })
    const retry = fire(page, 'scroll-view', 'refresherrefresh')
    page.flushTimers()
    await retry
    expect(page.public.refreshError).toBe('')
    expect(page.public.boardRating).toBe(0)
  })

  test('continuous paging keeps records, creates unique keys, honors category after switches and refresh', async () => {
    const page = mount('pages/task-board')
    const original = copy(page.public.visibleTasks)
    const seen = new Set(['t1', 't2', 't3'])
    ;['全部', '工作', '生活', '生活'].forEach(category => {
      fire(page, 'segmented-control', 'change', {}, { controlKey: 'category', value: category })
      const before = page.public.visibleTasks.length
      fire(page, 'scroll-view', 'scrolltolower')
      expect(page.public.visibleTasks.length).toBe(before + 2)
      page.public.visibleTasks.slice(-2).forEach(task => {
        expect(task.category).toBe(category === '全部' ? '工作' : category)
        expect(task.completed).toBe(false)
        expect(seen.has(task.taskKey)).toBe(false)
        seen.add(task.taskKey)
      })
    })
    fire(page, 'segmented-control', 'change', {}, { controlKey: 'category', value: '全部' })
    expect(copy(page.public.visibleTasks.slice(0, 3))).toEqual(original)
    expect(page.public.visibleTasks.length).toBe(11)
    const refresh = fire(page, 'scroll-view', 'refresherrefresh')
    page.flushTimers()
    await refresh
    fire(page, 'scroll-view', 'scrolltolower')
    page.public.visibleTasks.slice(-2).forEach(task => expect(seen.has(task.taskKey)).toBe(false))
  })

  test('mock narrow window establishes finite height, custom navigation, resize and home action', () => {
    const page = mount('pages/task-board')
    expect(page.public.windowHeight).toBe(568)
    expect(page.public.navigationHeight).toBe(44)
    expect(page.public.capsuleInset).toBe(96)
    expect(page.public.bottomInset).toBe(20)
    page.host.getWindowInfo = () => ({ windowWidth: 280, windowHeight: 480, screenHeight: 480, statusBarHeight: 20 })
    page.hooks.resize.forEach(fn => fn())
    expect(page.public.windowHeight).toBe(480)
    fire(page, 'board-home', 'tap')
    expect(page.host.lastRoute).toBe('/pages/home')
  })
})

describe('option-style rating-selector public contract', () => {
  test('defaults, star list, immediate selection and exact detail', () => {
    const rating = mount('components/rating-selector')
    expect(copy(rating.props)).toEqual({ ratingKey: '', value: 0, max: 5, readonly: false, label: '请评分' })
    expect(rating.public.stars).toEqual([1, 2, 3, 4, 5])
    fire(rating, 'data-value', 'tap', { item: 4 })
    expect(rating.public.currentValue).toBe(4)
    expect(rating.events).toEqual([{ type: 'change', detail: { ratingKey: '', value: 4 } }])
  })

  test('parent value updates repeatedly, including 0, and max is reactive', async () => {
    const rating = mount('components/rating-selector', { value: 2, ratingKey: 'r1' })
    expect(rating.public.currentValue).toBe(2)
    await rating.update({ value: 5 })
    expect(rating.public.currentValue).toBe(5)
    await rating.update({ value: 0, max: 3 })
    expect(rating.public.currentValue).toBe(0)
    expect(rating.public.stars).toEqual([1, 2, 3])
    expect(rating.events).toEqual([])
  })

  test('readonly blocks touch/selection/events but permits controlled parent updates', async () => {
    const rating = mount('components/rating-selector', { value: 2, readonly: true })
    fire(rating, 'data-value', 'touchstart', { item: 4 })
    fire(rating, 'data-value', 'tap', { item: 4 })
    expect(rating.public.pressedValue).toBe(0)
    expect(rating.public.currentValue).toBe(2)
    expect(rating.events).toEqual([])
    await rating.update({ value: 1 })
    expect(rating.public.currentValue).toBe(1)
  })

  test('touchend/cancel release and two instances have independent press/selection state', () => {
    const a = mount('components/rating-selector', { ratingKey: 'a' })
    const b = mount('components/rating-selector', { ratingKey: 'b' })
    fire(a, 'data-value', 'touchstart', { item: 2 })
    expect(a.public.pressedValue).toBe(2)
    expect(b.public.pressedValue).toBe(0)
    fire(a, 'data-value', 'touchcancel', { item: 2 })
    expect(a.public.pressedValue).toBe(0)
    expect(a.events).toEqual([])
    fire(a, 'data-value', 'touchstart', { item: 3 })
    fire(a, 'data-value', 'touchend', { item: 3 })
    expect(a.public.pressedValue).toBe(0)
    fire(a, 'data-value', 'tap', { item: 3 })
    expect(b.public.currentValue).toBe(0)
    expect(a.events[0].detail).toEqual({ ratingKey: 'a', value: 3 })
  })
})

describe('setup segmented-control public contract', () => {
  const options = [{ label: '甲', value: 'a' }, { label: '乙', value: 'b' }, { label: '禁用项', value: 'c', disabled: true }]

  test('defaults, missing/empty/null/async array options remain safe for wx:for', async () => {
    const segmented = mount('components/segmented-control')
    expect(copy(segmented.props)).toEqual({ controlKey: '', options: [], value: '', disabled: false, label: '请选择' })
    expect(segmented.public.safeOptions).toEqual([])
    await segmented.update({ options: null })
    expect(segmented.public.safeOptions).toEqual([])
    await segmented.update({ options })
    expect(copy(segmented.public.safeOptions)).toEqual(options)
    await segmented.update({ options: [] })
    expect(segmented.public.safeOptions).toEqual([])
  })

  test('immediate selection, exact detail, repeated parent value updates', async () => {
    const segmented = mount('components/segmented-control', { controlKey: 's1', options, value: 'a' })
    fire(segmented, 'data-index', 'tap', { index: 1 })
    expect(segmented.public.selectedValue).toBe('b')
    expect(segmented.events).toEqual([{ type: 'change', detail: { controlKey: 's1', value: 'b' } }])
    await segmented.update({ value: 'b' })
    await segmented.update({ value: 'a' })
    expect(segmented.public.selectedValue).toBe('a')
    await segmented.update({ value: '' })
    expect(segmented.public.selectedValue).toBe('')
    expect(segmented.events.length).toBe(1)
  })

  test('whole-control and single-option disabling preserve selection and event state', async () => {
    const segmented = mount('components/segmented-control', { options, value: 'a' })
    fire(segmented, 'data-index', 'touchstart', { index: 2 })
    fire(segmented, 'data-index', 'tap', { index: 2 })
    expect(segmented.public.pressedIndex).toBe(-1)
    expect(segmented.public.selectedValue).toBe('a')
    expect(segmented.events).toEqual([])
    await segmented.update({ disabled: true })
    fire(segmented, 'data-index', 'touchstart', { index: 1 })
    fire(segmented, 'data-index', 'tap', { index: 1 })
    expect(segmented.public.pressedIndex).toBe(-1)
    expect(segmented.public.selectedValue).toBe('a')
    expect(segmented.events).toEqual([])
    await segmented.update({ value: 'b' })
    expect(segmented.public.selectedValue).toBe('b')
  })

  test('touchend/cancel and instances isolate state; disabling during press releases it', async () => {
    const a = mount('components/segmented-control', { options })
    const b = mount('components/segmented-control', { options })
    fire(a, 'data-index', 'touchstart', { index: 1 })
    expect(a.public.pressedIndex).toBe(1)
    expect(b.public.pressedIndex).toBe(-1)
    fire(a, 'data-index', 'touchcancel', { index: 1 })
    expect(a.public.pressedIndex).toBe(-1)
    expect(a.events).toEqual([])
    fire(a, 'data-index', 'touchstart', { index: 0 })
    fire(a, 'data-index', 'touchend', { index: 0 })
    expect(a.public.pressedIndex).toBe(-1)
    fire(a, 'data-index', 'tap', { index: 0 })
    expect(b.public.selectedValue).toBe('')
    fire(a, 'data-index', 'touchstart', { index: 1 })
    await a.update({ disabled: true })
    expect(a.public.pressedIndex).toBe(-1)
  })
})

describe('page actually mounts both registered components and writes back public change events', () => {
  test('route initializes segmented value; selection and rating flow both directions; refresh resets child', async () => {
    const page = mount('pages/task-board')
    page.load({ category: '生活' })
    const segmented = mountChild(page, 'segmented-control')
    const rating = mountChild(page, 'rating-selector')
    expect(segmented.props.controlKey).toBe('category')
    expect(segmented.public.selectedValue).toBe('生活')
    expect(rating.props.ratingKey).toBe('board')
    expect(rating.props.max).toBe(5)
    expect(rating.props.readonly).toBe(false)
    fire(segmented, 'data-index', 'tap', { index: 1 })
    expect(page.public.category).toBe('工作')
    expect(page.public.visibleTasks.map(task => task.taskKey)).toEqual(['t1'])
    await segmented.sync()
    fire(rating, 'data-value', 'tap', { item: 5 })
    expect(page.public.boardRating).toBe(5)
    await rating.sync()
    expect(rating.public.currentValue).toBe(5)
    const refresh = fire(page, 'scroll-view', 'refresherrefresh')
    page.flushTimers()
    await refresh
    await rating.sync()
    expect(rating.public.currentValue).toBe(0)
    await tick()
  })
})

const fs = require('fs')
const path = require('path')
const vm = require('vm')
const source = fs.readFileSync(path.join(__dirname, '../outputs/user-list.mpx'), 'utf8')
const row = fs.readFileSync(path.join(__dirname, '../outputs/row.wxml'), 'utf8')
let options
const wx = { navigateTo: jest.fn() }
vm.runInNewContext(source.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/import[^\n]+/, ''), { createComponent: value => { options = value }, wx })
const state = () => Object.assign({}, options.data, options.methods)
test('initial, pending, null and repeated array updates produce arrays; visible rows use filtered indices', () => {
  const instance = state()
  expect(Array.isArray(options.initData.visibleItems)).toBe(true)
  expect(options.computed.visibleItems.call(instance)).toEqual([])
  instance.setRows({ items: null })
  expect(options.computed.visibleItems.call(instance)).toEqual([])
  instance.setRows({ items: [{ id: 1, name: 'hidden', visible: false }, { id: 2, name: 'A', visible: true }, { id: 3, name: 'B', visible: true }] })
  expect(options.computed.visibleItems.call(instance).map((item, index) => `${index}:${item.name}`)).toEqual(['0:A', '1:B'])
  instance.setRows({ items: [] })
  expect(options.computed.visibleItems.call(instance)).toEqual([])
  expect(source).toContain('data="{{item, index}}"')
  expect(row).toContain('<template name="user-row"><text>{{index}}:{{item.name}}</text>')
  expect(source).not.toContain('<include')
})
test.each(['skyline', 'webview'])('instance query scrolls actual users target under %s', renderer => {
  const scrollTo = jest.fn()
  const instance = state()
  instance.renderer = renderer
  options.attached.call(instance)
  expect(instance.isSkyline).toBe(renderer === 'skyline')
  const query = { select: jest.fn(function () { return this }), node: jest.fn(function () { return this }), exec: fn => fn([{ node: { scrollTo } }]) }
  instance.createSelectorQuery = () => query
  instance.scrollTop()
  expect(query.select).toHaveBeenCalledWith('#users')
  expect(scrollTo).toHaveBeenCalledWith({ top: 0 })
  expect(source.match(/<scroll-view id="users"[^>]+>/)[0]).toContain('enhanced="{{true}}"')
})
test('both detail entries route to detail', () => {
  expect(source).toContain('<navigator url="/pages/detail"><text>详情</text></navigator>')
  expect(source).toContain('<view bindtap="openDetail"><view><text>卡片详情</text></view></view>')
  state().openDetail()
  expect(wx.navigateTo).toHaveBeenCalledWith({ url: '/pages/detail' })
})
test('same button presses, releases and cancels with CSS feedback', () => {
  const instance = state()
  instance.press()
  expect(instance.pressed).toBe(true)
  instance.release()
  expect(instance.pressed).toBe(false)
  instance.press()
  instance.release()
  expect(instance.pressed).toBe(false)
  expect(source).toContain('bindtouchend="release" bindtouchcancel="release"')
  expect(source).toContain('transition: transform 150ms, opacity 150ms')
  expect(source).toContain('transform: scale(.96); opacity: .7')
  expect(source).not.toContain('createAnimation')
})
test('same paragraph title, runtime inline image, pulse and public data contracts', () => {
  expect(source).toMatch(/mpxTagName@wx="span"[^>]+max-lines="\{\{1\}\}" overflow="ellipsis"><image[^>]+inline-block[^>]+\/><text>{{label}}<\/text><\/view>/)
  expect(source).toContain('text-overflow: ellipsis')
  expect(source).toContain('animation: user-list-pulse 1s infinite')
  expect(source).toContain('width: 8px; height: 8px; border-radius: 4px; background: #f50')
  expect(options.properties.label.value).toBe('用户')
  expect(options.properties.payload.optionalTypes[0].name).toBe('Object')
  expect(options.data.config.default).toBe('keep')
})

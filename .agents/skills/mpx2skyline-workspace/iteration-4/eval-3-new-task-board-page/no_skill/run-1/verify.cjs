const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const assert = require('node:assert/strict')
const source = fs.readFileSync(path.join(__dirname, '../outputs/pages/task-board.mpx'), 'utf8')
const script = source.match(/<script setup>([\s\S]*?)<\/script>/)[1].replace(/import[^\n]+\n/, '')
function setup (query = {}) {
  let hook
  const toasts = []
  const context = { ref: value => ({ value }), computed: fn => ({ get value () { return fn() } }), onLoad: fn => { hook = fn }, setTimeout, wx: { getWindowInfo: () => ({ statusBarHeight: 24 }), showToast: item => toasts.push(item) } }
  vm.createContext(context)
  vm.runInContext(script + '\nglobalThis.api = { tasks, category, pressedCategory, refreshing, safeTop, filteredTasks, selectCategory, pressCategory, releaseCategory, toggleTask, refreshTasks, appendTasks };', context)
  hook(query)
  return { api: context.api, toasts }
}
const event = dataset => ({ currentTarget: { dataset } })
async function main () {
  const { api: a } = setup({ category: '生活' })
  assert.equal(a.category.value, '生活'); assert.equal(a.filteredTasks.value.length, 2)
  assert.equal(setup({ category: 'invalid' }).api.category.value, '全部')
  assert.equal(setup().api.filteredTasks.value.length, 3)
  assert.equal(a.safeTop.value, 24)
  console.log('PASS parameter initialization and filtering')
  a.toggleTask(event({ key: 't2' })); assert.equal(a.tasks.value[1].completed, true)
  a.toggleTask(event({ key: 't2' })); assert.equal(a.tasks.value[1].completed, false)
  a.selectCategory(event({ category: '工作' })); assert.equal(a.filteredTasks.value.length, 1)
  console.log('PASS completion toggle and category switching')
  a.tasks.value = []; assert.equal(a.filteredTasks.value.length, 0)
  assert.match(source, /wx:if="{{!filteredTasks.length}}"[^]*?暂无任务/)
  console.log('PASS empty data and empty-state template')
  const pending = a.refreshTasks(); assert.equal(a.refreshing.value, true); await pending
  assert.equal(a.refreshing.value, false); assert.equal(a.tasks.value.length, 3)
  assert.equal(a.tasks.value[1].completed, false)
  console.log('PASS refresh success and feedback cleanup')
  const { api: b, toasts } = setup({ refreshFail: '1' })
  const before = b.tasks.value
  await b.refreshTasks(); assert.equal(b.tasks.value, before); assert.equal(b.refreshing.value, false); assert.equal(toasts.length, 1)
  b.toggleTask(event({ key: 't1' })); assert.equal(b.tasks.value[0].completed, true)
  await b.refreshTasks(); assert.equal(b.tasks.value[0].completed, false)
  console.log('PASS refresh failure preserves usable list, retry succeeds')
  const existing = b.tasks.value.slice()
  b.appendTasks(); b.appendTasks(); assert.equal(b.tasks.value.length, 7)
  existing.forEach((task, index) => assert.equal(b.tasks.value[index], task))
  assert.equal(new Set(b.tasks.value.map(task => task.taskKey)).size, 7)
  b.tasks.value.slice(3).forEach(task => { assert.equal(task.category, '工作'); assert.equal(task.completed, false) })
  b.selectCategory(event({ category: '生活' })); b.appendTasks()
  assert.equal(b.tasks.value.length, 9); assert.equal(b.filteredTasks.value.length, 4)
  assert.equal(new Set(b.tasks.value.map(task => task.taskKey)).size, 9)
  console.log('PASS consecutive pagination, identity preservation, category and unique keys')
  b.pressCategory(event({ category: '工作' })); assert.equal(b.pressedCategory.value, '工作')
  b.releaseCategory(); assert.equal(b.pressedCategory.value, '')
  assert.match(source, /bindtouchcancel="releaseCategory"/)
  assert.match(source, /scale\(0\.96\); opacity: 0\.7/)
  assert.match(source, /transition: transform 150ms, opacity 150ms/)
  console.log('PASS touch cancel handler and declared feedback styles')
  const app = JSON.parse(fs.readFileSync(path.join(__dirname, '../outputs/app.json'), 'utf8'))
  assert.deepEqual(app.pages, ['pages/home', 'pages/task-board'])
  assert.deepEqual(app.window, { navigationBarTitleText: '演示' })
  assert.deepEqual(app.rendererOptions.webview, {})
  const page = JSON.parse(source.match(/<script name="json">([\s\S]*?)<\/script>/)[1])
  assert.equal(page.renderer, 'skyline'); assert.equal(page.componentFramework, 'glass-easel'); assert.equal(page.navigationStyle, 'custom')
  assert.match(source, /task-scroll \{ flex: 1; height: 0; min-height: 0/)
  assert.match(source, /max-lines="1"/); assert.match(source, /text-overflow: ellipsis/)
  console.log('PASS app preservation, page JSON, bounded scroll and title truncation declarations')
  console.log('ALL 8 CHECK GROUPS PASSED. Mock/static only; no renderer or compiler assertions.')
}
main().catch(error => { console.error(error); process.exitCode = 1 })

const fs = require('fs')
const path = require('path')
const vm = require('vm')
const out = path.join(__dirname, '../outputs')
const sfc = fs.readFileSync(path.join(out, 'orders.mpx'), 'utf8')
const source = sfc.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/^import .*$/gm, '')
const service = fs.readFileSync(path.join(out, 'service.js'), 'utf8').replace('export function', 'function')
function page (renderer = 'skyline') {
  let config
  vm.runInNewContext(service + '\n' + source, { createPage: value => { config = value }, wx: { getWindowInfo: () => ({ windowHeight: 800, statusBarHeight: 24 }) } })
  const p = Object.assign({}, config.data, config.methods, { renderer })
  p.onLoad = config.onLoad.bind(p)
  return p
}
test('initial load, two pages, refresh success/failure and recovery', async () => {
  const p = page()
  await p.onLoad()
  expect(p.sections.length).toBe(4)
  expect(p.sections.every(s => s.items.length === 8)).toBe(true)
  expect(p.bodyHeight).toBe(732)
  const initial = p.sections.slice()
  await p.loadMore()
  await p.loadMore()
  expect(p.pageNo).toBe(3)
  expect(p.sections.length).toBe(12)
  expect(p.sections.slice(0, 4)).toEqual(initial)
  expect(new Set(p.sections.map(s => s.id)).size).toBe(12)
  expect(new Set(p.sections.flatMap(s => s.items.map(i => i.id))).size).toBe(96)
  const retained = p.sections
  await p.reload(true)
  expect(p.sections).toBe(retained)
  expect(p.pageNo).toBe(3)
  expect(p.refreshing).toBe(false)
  expect(p.loading).toBe(false)
  expect(p.error).toBe('订单加载失败')
  await p.onRefresh()
  expect(p.sections.length).toBe(4)
  expect(p.pageNo).toBe(1)
  expect(p.refreshing).toBe(false)
  await p.loadMore()
  expect(p.pageNo).toBe(2)
  console.log('initial=4x8; pagination=8,12 groups; failure retained=12; refresh=4; recovery page=2')
})
test('main scroll, horizontal isolation, modal and WebView renderer branch', async () => {
  const p = page('webview')
  await p.onLoad()
  expect(p.isSkyline).toBe(false)
  p.onMainScroll({ detail: { scrollTop: 137 } })
  p.ignoreScroll({ detail: { scrollTop: 0, scrollLeft: 80 } })
  expect(p.scrollTop).toBe(137)
  p.open()
  expect(p.opened).toBe(true)
  p.close()
  expect(p.opened).toBe(false)
  expect(sfc).toContain('catchscroll="onMainScroll"')
  expect(sfc.match(/catchscroll="ignoreScroll"/g).length).toBe(2)
  expect(sfc).not.toMatch(/onPageScroll|onReachBottom|onPullDownRefresh/)
  console.log('main scrollTop=137; horizontal ignored; modal open/close; WebView branch=false')
})

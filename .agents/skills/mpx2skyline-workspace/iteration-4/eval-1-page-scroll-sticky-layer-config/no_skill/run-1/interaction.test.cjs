const fs = require('fs')
const path = require('path')
const vm = require('vm')
const assert = require('assert/strict')
const out = path.resolve(__dirname, '../outputs')
const source = fs.readFileSync(path.join(out, 'orders.mpx'), 'utf8')
const service = fs.readFileSync(path.join(out, 'service.js'), 'utf8')
let definition
vm.runInNewContext(service.replace('export function', 'function') + '\n' + source.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/^import .*$/gm, ''), {
  createPage: value => { definition = value },
  wx: { getWindowInfo: () => ({ windowHeight: 844, statusBarHeight: 44 }) }
})
async function verify () {
  const page = Object.assign({}, definition.data, definition.methods, { renderer: 'skyline' })
  page.updateSize()
  assert.equal(page.bodyHeight, 756)
  await page.reload()
  assert.equal(page.sections.length, 4)
  assert.ok(page.sections.every(group => group.items.length === 8))
  const original = page.sections
  await page.loadMore()
  await page.loadMore()
  assert.equal(page.pageNo, 3)
  assert.equal(page.sections.length, 12)
  original.forEach((group, index) => assert.equal(page.sections[index], group))
  assert.equal(new Set(page.sections.map(group => group.id)).size, 12)
  assert.equal(new Set(page.sections.flatMap(group => group.items.map(item => item.id))).size, 96)
  console.log('PASS initial page 4 x 8; two pagination requests yield 12 groups / 96 unique orders; retained original group references')
  const beforeFailure = page.sections
  await page.reload(true)
  assert.equal(page.sections, beforeFailure)
  assert.equal(page.pageNo, 3)
  assert.equal(page.refreshing, false)
  assert.equal(page.loading, false)
  assert.equal(page.error, '订单加载失败')
  console.log('PASS injected refresh failure preserves list/page and ends refresher')
  await page.onRefresh()
  assert.equal(page.pageNo, 1)
  assert.equal(page.sections.length, 4)
  assert.equal(page.refreshing, false)
  assert.equal(page.error, '')
  page.onMainScroll({ detail: { scrollTop: 237 } })
  assert.equal(page.scrollTop, 237)
  page.open()
  assert.equal(page.opened, true)
  page.close()
  assert.equal(page.opened, false)
  console.log('PASS refresh recovery replaces list; main scroll position=237; modal open/close')
  assert.ok(!/onPullDownRefresh|onReachBottom|onPageScroll|stopPullDownRefresh/.test(source))
  assert.equal((source.match(/bindrefresherrefresh="onRefresh"/g) || []).length, 2)
  const app = JSON.parse(fs.readFileSync(path.join(out, 'app.json'), 'utf8'))
  assert.equal(app.pages[0], 'pages/home')
  assert.equal(app.window.navigationBarTitleText, '演示')
  assert.ok(app.rendererOptions.webview)
  assert.equal(app.componentFramework, 'glass-easel')
  console.log('PASS static event ownership and retained app configuration')
}
if (typeof test === 'function') test('orders refresh, pagination and scroll contracts', verify)
else verify().catch(error => { console.error(error); process.exitCode = 1 })

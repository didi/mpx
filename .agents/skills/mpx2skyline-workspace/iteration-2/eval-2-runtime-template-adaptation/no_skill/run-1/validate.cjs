const fs = require('fs')
const vm = require('vm')
const assert = require('assert/strict')
const source = fs.readFileSync('../outputs/user-list.mpx', 'utf8')
const row = fs.readFileSync('../outputs/row.wxml', 'utf8')
let options
const script = source.match(/<script>([\s\S]*?)<\/script>/)[1].replace(/import[^\n]+\n/, '')
vm.runInNewContext(script, { createComponent (value) { options = value } })
assert.equal(options.properties.label.value, '用户')
assert.equal(options.properties.payload.type.name, 'String')
assert.equal(options.properties.payload.optionalTypes[0].name, 'Object')
assert.equal(options.properties.payload.value, '')
assert.equal(options.data.config.default, 'keep')
const queue = []
const instance = Object.assign({}, options.data, options.methods, { $nextTick (callback) { queue.push(callback) } })
const visible = () => options.computed.visibleItems.call(instance)
assert.equal(visible().length, 0)
assert.equal(visible().length, 0)
instance.setRows({ items: null })
assert.equal(visible().length, 0)
instance.setRows({ items: [{ id: 1, visible: true }, { id: 2, visible: false }] })
assert.equal(visible().length, 1)
assert.equal(visible()[0].id, 1)
instance.setRows({ items: [] })
assert.equal(visible().length, 0)
for (const top of [0, 350, 720]) {
  instance.onScroll({ detail: { scrollTop: top } })
  instance.scrollTop()
  assert.equal(instance.scrollTopValue, top)
  queue.shift()()
  assert.equal(instance.scrollTopValue, 0)
}
assert.match(source, /<import src="\.\/row\.wxml"\/>/)
assert.match(source, /<template is="user-row" data="\{\{item, index\}\}"\/>/)
assert.match(row, /<template name="user-row">/)
assert.match(source, /scroll-top="\{\{scrollTopValue\}\}"/)
assert.match(source, /bindscroll="onScroll"/)
assert.doesNotMatch(source, /<include|#1users|type:\s*\[/)
assert.equal(JSON.parse(source.match(/<script type="application\/json">([\s\S]*?)<\/script>/)[1]).component, true)
assert.match(source, /\.user-scroll\s*\{\s*height: 300px;/)
console.log('PASS: property declarations/defaults, config.default preservation, initial/null/array/filter loop data, repeated scroll-to-top state updates, relative template linkage, class style and component JSON.')
console.log('LIMITATION: script assertions use a stub createComponent/$nextTick; no Mpx compilation or WeChat WebView/Skyline runtime was executed.')
